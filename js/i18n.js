  const GMAIL_COMPOSE = 'https://mail.google.com/mail/?view=cm&fs=1&to=' + encodeURIComponent(GMAIL) + '&su=' + encodeURIComponent('Inquiry — Logistik Transport Gesamt');

  function detectLang() {
    var saved = localStorage.getItem('ltg_lang');
    if (saved && I18N[saved]) return { lang: saved, source: 'saved' };

    var params = new URLSearchParams(location.search);
    if (params.get('lang') && I18N[params.get('lang')]) return { lang: params.get('lang'), source: 'url' };

    var nav = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    if (nav.startsWith('de')) return { lang: 'de', source: 'browser' };
    if (nav.startsWith('fr')) return { lang: 'fr', source: 'browser' };
    if (nav.startsWith('en')) return { lang: 'en', source: 'browser' };

    return { lang: 'en', source: 'default' };
  }

  async function detectByCountry() {
    try {
      var ctrl = new AbortController();
      var t = setTimeout(function () { ctrl.abort(); }, 2500);
      var res = await fetch('https://ipapi.co/json/', { signal: ctrl.signal });
      clearTimeout(t);
      if (!res.ok) return null;
      var data = await res.json();
      var cc = (data.country_code || '').toUpperCase();
      if (COUNTRY_LANG[cc]) return { lang: COUNTRY_LANG[cc], country: cc, source: 'geo' };
    } catch (e) { /* offline / blocked */ }
    return null;
  }

  function t(key) {
    var lang = window.LTG_LANG || 'en';
    return (I18N[lang] && I18N[lang][key]) || (I18N.en && I18N.en[key]) || (I18N.de && I18N.de[key]) || key;
  }

  function applyLang(lang, opts) {
    if (!I18N[lang]) lang = 'en';
    window.LTG_LANG = lang;
    localStorage.setItem('ltg_lang', lang);
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var val = t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        // skip textContent for inputs
      } else if (el.hasAttribute('data-i18n-html')) {
        el.innerHTML = val.replace(/\n/g, '<br>');
      } else {
        el.textContent = val;
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });

    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      var base = el.getAttribute('data-i18n-title');
      if (base) document.title = t(base) + ' — Logistik Transport Gesamt';
    });

    document.querySelectorAll('.lang-switch button').forEach(function (btn) {
      btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    // Gmail links
    document.querySelectorAll('a[data-gmail]').forEach(function (a) {
      a.href = GMAIL_COMPOSE;
    });
    document.querySelectorAll('a[data-mailto]').forEach(function (a) {
      a.href = 'mailto:' + GMAIL;
    });

    if (opts && opts.toast) {
      var toast = document.getElementById('langToast');
      if (toast) {
        var lbl = I18N[lang].name;
        toast.textContent = t('lang_detected') + ': ' + I18N[lang].flag + ' ' + lbl + ' — ' + t('lang_set') + ' ' + lbl;
        toast.classList.add('show');
        setTimeout(function () { toast.classList.remove('show'); }, 3500);
      }
    }

    window.dispatchEvent(new CustomEvent('ltg:lang', { detail: { lang: lang } }));
  }

  function buildLangSwitch() {
    document.querySelectorAll('.lang-switch').forEach(function (box) {
      box.innerHTML = ['en', 'de', 'fr'].map(function (l) {
        return '<button type="button" data-lang="' + l + '" title="' + I18N[l].name + '">' + I18N[l].flag + ' ' + l.toUpperCase() + '</button>';
      }).join('');
      box.querySelectorAll('button').forEach(function (btn) {
        btn.addEventListener('click', function () { applyLang(btn.dataset.lang, { toast: true }); });
      });
    });
  }

  window.LTG = { I18N: I18N, t: t, applyLang: applyLang, GMAIL: GMAIL, GMAIL_COMPOSE: GMAIL_COMPOSE };

  document.addEventListener('DOMContentLoaded', async function () {
    buildLangSwitch();
    var initial = detectLang();
    applyLang(initial.lang, { toast: false });

    // Auto by country only if user never chose manually
    if (initial.source !== 'saved' && initial.source !== 'url') {
      var geo = await detectByCountry();
      if (geo && geo.lang !== window.LTG_LANG) {
        applyLang(geo.lang, { toast: true });
      }
    }
  });
